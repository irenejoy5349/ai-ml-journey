# if else

num = 15

if num % 2 == 0:
    print("Even Number")
else:
    print("Odd Number")

print("----------------")

# if elif else

marks = 78

if marks >= 90:
    print("Grade A")
elif marks >= 75:
    print("Grade B")
elif marks >= 50:
    print("Grade C")
else:
    print("Fail")
