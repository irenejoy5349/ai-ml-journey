# Arithmetic Operators

a = 10
b = 5

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a // b)
print(a ** b)



# Comparison Operators

x = 20
y = 15

print(x == y)
print(x != y)
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)



# Assignment Operators

num = 10

num += 5
print(num)

num -= 2
print(num)

num *= 3
print(num)



# Logical Operators

a = True
b = False

print(a and b)
print(a or b)
print(not a)
