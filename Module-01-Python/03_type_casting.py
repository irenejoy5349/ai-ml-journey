# Type Casting

# String to Integer

num = "10"

print(num)
print(type(num))

num = int(num)

print(num)
print(type(num))

print("----------------")

# Integer to Float

age = 22

print(age)
print(type(age))

age = float(age)

print(age)
print(type(age))

print("----------------")

# Float to Integer

price = 99.9

print(price)
print(type(price))

price = int(price)

print(price)
print(type(price))

print("----------------")

# Integer to String

marks = 95

print(marks)
print(type(marks))

marks = str(marks)

print(marks)
print(type(marks))
